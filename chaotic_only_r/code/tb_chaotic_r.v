// ============================================================================
// File: tb_chaotic_r.v
// Module: tb_chaotic_r
// Description: Testbench for Standalone Chaotic Generator (R-Channel Only, No LFSR)
//              Generates and saves 1,000,000 bits into 'chaotic_r_1m_bits.txt'
//              for NIST SP 800-22 and statistical randomness analysis.
// ============================================================================

`timescale 1ns/1ps
`include "chaotic_r.v"

module tb_chaotic_r;

    parameter TOTAL_BITS = 1000000; // 1 Million bits for NIST testing
    parameter CLK_PERIOD = 10;      // 10 ns = 100 MHz clock

    reg clk;
    reg rst;
    reg enable;

    wire        chaotic_bit;
    wire [7:0]  R_out;
    wire        key_ready;
    wire signed [15:0] x_state;

    integer file_id;
    integer bit_count  = 0;
    integer byte_count = 0;

    // Instantiate Unit Under Test
    chaotic_r #(
        .CHAOTIC_INIT_SEED(16'sh7EF0)
    ) uut (
        .clk(clk),
        .rst(rst),
        .enable(enable),
        .chaotic_bit(chaotic_bit),
        .R_out(R_out),
        .key_ready(key_ready),
        .x_state(x_state)
    );

    // 100 MHz clock generation (10 ns period)
    always #(CLK_PERIOD / 2) clk = ~clk;

    initial begin
        $display("============================================================================");
        $display(" Starting Simulation: Standalone Chaotic Generator (R-Channel Only, No LFSR)");
        $display(" Target: Generating %0d bits into 'chaotic_r_1m_bits.txt'", TOTAL_BITS);
        $display("============================================================================");

        // Open output file
        file_id = $fopen("chaotic_r_1m_bits.txt", "w");
        if (file_id == 0) begin
            $display("[ERROR] Could not open output file 'chaotic_r_1m_bits.txt'");
            $finish;
        end

        // 1. Initialize & Reset
        clk       = 0;
        rst       = 1;
        enable    = 0;
        bit_count = 0;

        #(CLK_PERIOD * 2.5);
        rst = 0;
        #(CLK_PERIOD * 1.5);
        enable = 1;

        // Allow pipeline to prime (5 pipeline stages)
        repeat (5) @(posedge clk);
        $display("[TB] 5-stage pipeline primed. Starting bit collection to file...");
    end

    // Log each bit every clock cycle to file
    always @(posedge clk) begin
        if (enable && !rst && bit_count < TOTAL_BITS) begin
            $fwrite(file_id, "%b", chaotic_bit);
            bit_count <= bit_count + 1;

            // Report progress every 100,000 bits
            if ((bit_count + 1) % 100000 == 0) begin
                $display("  [%0t ns] Logged %0d / %0d bits (%0d%%)...", 
                         $time, bit_count + 1, TOTAL_BITS, ((bit_count + 1) * 100) / TOTAL_BITS);
            end

            // Stop when 1 million bits are collected
            if (bit_count + 1 == TOTAL_BITS) begin
                $display("\n============================================================================");
                $display("  [SUCCESS] Collected all %0d bits into 'chaotic_r_1m_bits.txt'!", TOTAL_BITS);
                $display("  File ready for NIST SP 800-22 testing.");
                $display("============================================================================");
                $fclose(file_id);
                $finish;
            end
        end
    end

    // Preview first few generated bytes to console
    always @(posedge clk) begin
        if (key_ready && byte_count < 5) begin
            byte_count <= byte_count + 1;
            $display("  [Debug Preview] Byte #%0d: R_out = 0x%02h (%08b) | x = 0x%04h", 
                     byte_count + 1, R_out, R_out, x_state);
        end
    end

endmodule
